import AppKit

private final class FakeHistoryPasteboard {
    var generation = 0
    var types: [NSPasteboard.PasteboardType] = []
    var items: [[NSPasteboard.PasteboardType]] = []
    var values: [NSPasteboard.PasteboardType: Data] = [:]
    var metadataReads = 0
    var dataReads = 0
    var writes = 0
    var failWrite = false
    var duringMetadata: (() -> Void)?
    var duringData: (() -> Void)?
    var afterWrite: (() -> Void)?

    func external(_ text: String) { external([.string: Data(text.utf8)]) }

    func external(_ data: [NSPasteboard.PasteboardType: Data],
                  rootTypes: [NSPasteboard.PasteboardType]? = nil,
                  itemTypes: [[NSPasteboard.PasteboardType]]? = nil) {
        generation += 1
        values = data
        types = rootTypes ?? Array(data.keys)
        items = itemTypes ?? [Array(data.keys)]
    }

    var environment: ClipboardHistoryMonitor.Environment {
        .init(changeCount: { [unowned self] in generation }, metadata: { [unowned self] in
            metadataReads += 1
            let value = ClipboardHistoryMonitor.Metadata(rootTypes: types, itemTypes: items)
            duringMetadata?()
            return value
        }, data: { [unowned self] type in
            dataReads += 1
            let value = values[type]
            duringData?()
            return value
        }, write: { [unowned self] data, type in
            writes += 1
            guard !failWrite else { return nil }
            external([type: data])
            let ownGeneration = generation
            afterWrite?()
            return ownGeneration
        })
    }
}

private final class HistoryMonitorFixture {
    let suite = "ClipboardHistoryMonitorTests-" + UUID().uuidString
    let defaults: UserDefaults
    let board = FakeHistoryPasteboard()
    let store = ClipboardHistoryStore(directoryURL: nil)
    let monitor: ClipboardHistoryMonitor

    init(start: Bool = true) {
        defaults = UserDefaults(suiteName: suite)!
        monitor = ClipboardHistoryMonitor(store: store, defaults: defaults, environment: board.environment)
        if start { monitor.start() }
    }

    deinit {
        monitor.stop()
        defaults.removePersistentDomain(forName: suite)
    }
}

@main
enum ClipboardHistoryMonitorTests {
    private static var assertions = 0

    static func check(_ value: @autoclosure () -> Bool, _ message: String,
                      file: StaticString = #file, line: UInt = #line) {
        precondition(value(), message, file: file, line: line)
        assertions += 1
    }

    static func main() {
        baselineAndPolling()
        protectedMetadata()
        externalReadRaces()
        copyRestoreAndPause()
        writeFailuresAndRaces()
        imageAndSizeValidation()
        privatePasteboardIntegration()
        print("ClipboardHistoryMonitorTests passed: \(assertions) checks for baselines, polling, pause, protected metadata before payload, external races, exact own writes, stable restoration, text-only exclusion and size limits; no general pasteboard access")
    }

    private static func baselineAndPolling() {
        let f = HistoryMonitorFixture(start: false)
        f.board.external("Existing clipboard is not imported at launch")
        f.monitor.start()
        f.monitor.checkForChanges()
        check(f.store.items.isEmpty && f.board.metadataReads == 0 && f.board.dataReads == 0, "start baselines without reading existing contents")
        check(f.monitor.isEnabled, "history defaults to enabled")
        f.board.external("new copy")
        f.monitor.start()
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "new copy", "duplicate start must not skip an unobserved copy")
        let reads = f.board.dataReads
        f.monitor.checkForChanges()
        check(f.board.dataReads == reads && f.store.items.count == 1, "unchanged generations are inert")

        f.board.external("timer copy")
        RunLoop.main.run(until: Date().addingTimeInterval(0.65))
        check(f.store.items.first?.text == "timer copy", "common-mode timer observes new copies")
        f.monitor.stop()
        f.board.external("while stopped")
        RunLoop.main.run(until: Date().addingTimeInterval(0.65))
        check(!f.store.items.contains { $0.text == "while stopped" }, "stop invalidates polling")
        f.monitor.start()
        f.monitor.checkForChanges()
        check(!f.store.items.contains { $0.text == "while stopped" }, "restart does not import the existing clipboard")
    }

    private static func protectedMetadata() {
        let f = HistoryMonitorFixture()
        let protected = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "net.antelle.keeweb",
                         "de.petermaurer.TransientPasteboardType", "Pasteboard generator type", "com.typeit4me.clipping"]
        for raw in protected {
            let marker = NSPasteboard.PasteboardType(raw)
            for rootOnly in [true, false] {
                f.board.external([.string: Data("synthetic protected value".utf8)],
                    rootTypes: rootOnly ? [.string, marker] : [.string],
                    itemTypes: rootOnly ? [[.string]] : [[.string, marker]])
                f.monitor.checkForChanges()
                check(f.board.dataReads == 0 && f.store.items.isEmpty, "root-only and item-only protection must precede all payload reads")
            }
        }
        f.board.external([.string: Data("file".utf8)], rootTypes: [.string, .fileURL])
        f.monitor.checkForChanges()
        f.board.external([.string: Data("two items".utf8)], itemTypes: [[.string], [.string]])
        f.monitor.checkForChanges()
        f.board.external([.pdf: Data([1, 2, 3])])
        f.monitor.checkForChanges()
        f.board.external([.string: Data("no item".utf8)], itemTypes: [])
        f.monitor.checkForChanges()
        check(f.board.dataReads == 0 && f.store.items.isEmpty, "files, unsupported payloads and non-single-item copies are not read")
    }

    private static func externalReadRaces() {
        let f = HistoryMonitorFixture()
        f.board.external("metadata old")
        f.board.duringMetadata = {
            f.board.duringMetadata = nil
            f.board.external("metadata new")
        }
        f.monitor.checkForChanges()
        check(f.store.items.isEmpty && f.board.dataReads == 0, "a metadata generation change prevents payload access")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "metadata new", "new generation remains eligible on the next poll")
        f.board.external("payload old")
        f.board.duringData = {
            f.board.duringData = nil
            f.board.external("payload new")
        }
        f.monitor.checkForChanges()
        check(!f.store.items.contains { $0.text == "payload old" }, "a changing payload is never stored")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "payload new", "read-race rejection does not swallow the subsequent copy")
    }

    private static func copyRestoreAndPause() {
        let f = HistoryMonitorFixture()
        var notifications = 0
        f.store.onChange = { notifications += 1 }
        f.board.external("external before dictation")
        check(f.monitor.copyText("dictated text"), "copyText writes text")
        check(f.store.items.map(\.text) == ["dictated text", "external before dictation"], "copyText preserves unpolled external content before replacing it")
        check(notifications > 0, "monitor preserves the store's existing onChange observer")
        let dictatedID = f.store.items[0].id
        f.monitor.checkForChanges()
        check(f.store.items.count == 2 && f.store.items[0].id == dictatedID, "own copy is immediately stored without a polling duplicate")
        check(f.monitor.copyText("dictated text") && f.store.items.count == 2 && f.store.items[0].id == dictatedID, "exact repeated copy keeps its stable identity")

        let externalItem = f.store.items[1]
        check(f.monitor.restore(externalItem), "restore succeeds")
        check(f.store.items.count == 2 && f.store.items[0].id == externalItem.id, "restore deduplicates and reorders the same identity")
        check(f.board.values[.string] == externalItem.data, "restore writes original data")
        f.monitor.checkForChanges()
        check(f.store.items.count == 2, "restore is not recaptured as another item")

        f.monitor.setEnabled(false)
        let pausedItems = f.store.items.map(\.id)
        let reads = f.board.dataReads
        f.board.external("paused external")
        f.monitor.checkForChanges()
        check(f.board.dataReads == reads, "paused observation does not read payloads")
        check(f.monitor.copyText("paused dictated text"), "paused history still permits copying")
        check(f.monitor.restore(externalItem), "paused history still permits restoring")
        check(f.store.items.map(\.id) == pausedItems, "paused writes neither add nor reorder history")
        let reopened = ClipboardHistoryMonitor(store: f.store, defaults: f.defaults, environment: f.board.environment)
        check(!reopened.isEnabled, "pause preference survives a new monitor")
        f.board.external("last paused value")
        f.monitor.setEnabled(true)
        f.monitor.checkForChanges()
        check(f.store.items.map(\.id) == pausedItems, "resuming baselines without importing paused content")
        f.board.external("after resume")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "after resume", "later copies resume normally")

        for index in 0..<10 {
            f.board.external("history \(index)")
            f.monitor.checkForChanges()
        }
        let oldest = f.store.items.last!
        f.board.external("new unpolled external")
        check(f.monitor.restore(oldest), "oldest selection remains restorable after preflight eviction")
        check(f.store.items.count == 10 && f.store.items.first?.data == oldest.data
              && f.store.items.contains { $0.text == "new unpolled external" }, "preflight and restored selection both remain within the ten-entry bound")
    }

    private static func writeFailuresAndRaces() {
        let f = HistoryMonitorFixture()
        f.board.external("safe previous copy")
        f.board.failWrite = true
        check(!f.monitor.copyText("failed write"), "write failure is returned")
        check(f.store.items.map(\.text) == ["safe previous copy"], "failed own content is never added")
        f.board.failWrite = false
        f.board.afterWrite = {
            f.board.afterWrite = nil
            f.board.external("interleaved external copy")
        }
        check(!f.monitor.copyText("superseded write"), "external replacement during write cannot be reported as current own content")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "interleaved external copy"
              && !f.store.items.contains { $0.text == "superseded write" }, "exact own-generation checks do not swallow external changes")
        check(f.monitor.copyText("successful own copy"), "normal write recovers")
        f.board.external("next external copy")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "next external copy", "a future external generation is not mistaken for an own write")

        f.board.external("preflight snapshot")
        f.store.onChange = {
            f.store.onChange = nil
            f.board.external("arrived after preflight")
        }
        let previousWrites = f.board.writes
        check(!f.monitor.copyText("would overwrite unseen content") && f.board.writes == previousWrites,
              "a copy arriving after preflight prevents destructive replacement")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "arrived after preflight", "unseen preflight race stays available for capture")
    }

    private static func image(_ type: NSBitmapImageRep.FileType, width: Int = 2) -> Data {
        let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: 2,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        memset(bitmap.bitmapData!, 255, bitmap.bytesPerRow * bitmap.pixelsHigh)
        return bitmap.representation(using: type, properties: [:])!
    }

    private static func imageAndSizeValidation() {
        let f = HistoryMonitorFixture()
        let png = image(.png)
        let tiff = image(.tiff)
        for values: [NSPasteboard.PasteboardType: Data] in [
            [.png: png], [.tiff: tiff],
            [.png: png, .string: Data("image fallback text".utf8)],
            [.tiff: tiff, .string: Data("another fallback".utf8)]
        ] {
            let reads = f.board.dataReads
            f.board.external(values)
            f.monitor.checkForChanges()
            check(f.board.dataReads == reads && f.store.items.isEmpty, "Image clipboard is skipped before reading any payload")
        }
        let imageItem = ClipboardHistoryItem(id: UUID(), kind: .png, data: png, createdAt: Date())
        check(!f.monitor.restore(imageItem) && f.board.writes == 0, "Legacy images cannot be restored in text-only mode")
        f.board.external("normal text")
        f.monitor.checkForChanges()
        check(f.store.items.first?.text == "normal text", "Normal text is retained after skipped images")
        for data in [Data(), Data([0xff, 0xfe]), Data(" \n\t".utf8), Data(repeating: 65, count: ClipboardHistoryMonitor.maximumItemByteCount + 1)] {
            f.board.external([.string: data])
            f.monitor.checkForChanges()
        }
        check(f.store.items.count == 1, "empty, malformed, blank and oversized text are rejected")
        let oversizedText = String(repeating: "a", count: ClipboardHistoryMonitor.maximumItemByteCount + 1)
        check(f.monitor.copyText(oversizedText) && f.board.values[.string] == Data(oversizedText.utf8),
              "history's size limit must not block actual text copying")
        f.monitor.checkForChanges()
        check(f.store.items.count == 1, "oversized own text is copied but never retained in history")
        check(!f.monitor.copyText(""), "empty text still does not clear the clipboard")
        let invalid = ClipboardHistoryItem(id: UUID(), kind: .png, data: Data("invalid".utf8), createdAt: Date())
        check(!f.monitor.restore(invalid), "restoring an invalid image does not write the clipboard")
    }

    private static func privatePasteboardIntegration() {
        let suite = "ClipboardHistoryPrivateBoardTests-" + UUID().uuidString
        let defaults = UserDefaults(suiteName: suite)!
        let board = NSPasteboard(name: .init("ClipboardHistoryPrivateBoard-" + UUID().uuidString))
        let store = ClipboardHistoryStore(directoryURL: nil)
        let monitor = ClipboardHistoryMonitor(store: store, pasteboard: board, defaults: defaults)
        defer {
            monitor.stop()
            board.releaseGlobally()
            defaults.removePersistentDomain(forName: suite)
        }
        board.clearContents()
        board.setString("existing private board", forType: .string)
        monitor.start()
        monitor.checkForChanges()
        check(store.items.isEmpty, "live environment baselines a named private pasteboard")
        board.clearContents()
        board.setString("private external copy", forType: .string)
        let beforeOwnWrite = board.changeCount
        check(monitor.copyText("private dictated copy"), "live environment writes one named-board generation")
        check(board.changeCount == beforeOwnWrite + 1,
              "actual clearContents plus writeObjects produces exactly the generation returned by clearContents")
        monitor.checkForChanges()
        check(store.items.map(\.text) == ["private dictated copy", "private external copy"], "actual AppKit counts suppress only the exact own write")
        let png = image(.png)
        board.clearContents()
        board.setData(png, forType: .png)
        monitor.checkForChanges()
        check(store.items.count == 2 && store.items.allSatisfy { $0.kind == .text }, "actual private pasteboard ignores PNG")
        let selected = store.items[0]
        check(monitor.restore(selected) && board.string(forType: .string) == selected.text, "actual private pasteboard restores the selected text")
        monitor.checkForChanges()
        check(store.items.count == 2 && store.items.first?.id == selected.id, "private-board restore keeps stable identity without a duplicate")
    }
}
