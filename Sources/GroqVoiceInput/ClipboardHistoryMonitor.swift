import AppKit

/// Reads only new, supported clipboard values. Restoring history never sends
/// keyboard events or changes another app's focus.
final class ClipboardHistoryMonitor {
    struct Metadata {
        var rootTypes: [NSPasteboard.PasteboardType]
        var itemTypes: [[NSPasteboard.PasteboardType]]
    }

    /// Separate metadata and payload access so exclusion always precedes data
    /// reads, and tests can model another process changing the pasteboard.
    struct Environment {
        var changeCount: () -> Int
        var metadata: () -> Metadata
        var data: (NSPasteboard.PasteboardType) -> Data?
        var write: (Data, NSPasteboard.PasteboardType) -> Int?

        static func live(_ pasteboard: NSPasteboard) -> Self {
            Self(changeCount: { pasteboard.changeCount }, metadata: {
                Metadata(rootTypes: pasteboard.types ?? [],
                         itemTypes: pasteboard.pasteboardItems?.map(\.types) ?? [])
            }, data: { pasteboard.data(forType: $0) }, write: { data, type in
                let item = NSPasteboardItem()
                guard item.setData(data, forType: type) else { return nil }
                let generation = pasteboard.clearContents()
                guard pasteboard.changeCount == generation,
                      pasteboard.writeObjects([item]),
                      pasteboard.changeCount == generation else { return nil }
                return generation
            })
        }
    }

    static let enabledPreferenceKey = "neighbor.clipboardHistory.enabled"
    static let maximumItemByteCount = 8 * 1024 * 1024
    // 密碼與敏感資料保護（Password Manager Exclusion）：
    // 1Password、KeeWeb 等密碼管理器在複製密碼時，會在 NSPasteboard 宣告特定標記型別（如 ConcealedType）。
    // 監控器在讀取資料 Payload 之前，優先檢驗 metadata 型別黑名單；
    // 只要含有任何隱私或暫存標記，直接整筆略過，徹底防止敏感密碼落入歷史資料庫。
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping"
    ]
    private static let fileReferenceTypes: Set<String> = [
        NSPasteboard.PasteboardType.fileURL.rawValue,
        "NSFilenamesPboardType",
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-file-content-type"
    ]

    private let store: ClipboardHistoryStore
    private let defaults: UserDefaults
    private let environment: Environment
    private var timer: Timer?
    private var observedChangeCount: Int?
    private var ownWriteChangeCount: Int?
    private(set) var isEnabled: Bool

    convenience init(store: ClipboardHistoryStore, pasteboard: NSPasteboard = .general,
                     defaults: UserDefaults = .standard) {
        self.init(store: store, defaults: defaults, environment: .live(pasteboard))
    }

    init(store: ClipboardHistoryStore, defaults: UserDefaults, environment: Environment) {
        self.store = store
        self.defaults = defaults
        self.environment = environment
        isEnabled = defaults.object(forKey: Self.enabledPreferenceKey) as? Bool ?? true
    }

    deinit { timer?.invalidate() }

    func start() {
        guard timer == nil else { return }
        baseline()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.checkForChanges()
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func setEnabled(_ enabled: Bool) {
        guard isEnabled != enabled else { return }
        isEnabled = enabled
        defaults.set(enabled, forKey: Self.enabledPreferenceKey)
        // Copies made while paused are not imported when observation resumes.
        baseline()
    }

    func checkForChanges() {
        let generation = environment.changeCount()
        guard let previous = observedChangeCount else {
            observedChangeCount = generation
            return
        }
        guard generation != previous else { return }
        observedChangeCount = generation
        // 自身寫入循環防止（Self-Write Suppression）：
        // 若當前 changeCount 與自身剛剛呼叫 write() 產生的 generation 相同，
        // 代表這筆變更是由本 App 的語音貼上或歷史還原操作所寫入，不應重複加入歷史，直接退出。
        guard generation != ownWriteChangeCount else { return }
        ownWriteChangeCount = nil
        guard isEnabled else { return }

        let metadata = environment.metadata()
        let types = Set(metadata.rootTypes + metadata.itemTypes.flatMap { $0 })
        let rawTypes = Set(types.map(\.rawValue))
        guard rawTypes.isDisjoint(with: Self.ignoredTypes),
              rawTypes.isDisjoint(with: Self.fileReferenceTypes),
              metadata.itemTypes.count == 1,
              environment.changeCount() == generation else { return }

        // Text-only history: ignore image representations before reading data,
        // even when an image advertises an incidental text fallback.
        guard types.contains(.string), !types.contains(.png), !types.contains(.tiff),
              let data = environment.data(.string),
              environment.changeCount() == generation,
              Self.accepts(data, kind: .text),
              environment.changeCount() == generation else { return }
        _ = store.add(kind: .text, data: data)
    }

    @discardableResult
    func copyText(_ text: String) -> Bool {
        // History's size/blank-content policy must not restrict actual copying.
        // The store independently decides whether this value can be retained.
        guard !text.isEmpty else { return false }
        let data = Data(text.utf8)
        checkForChanges()
        guard write(data, kind: .text) else { return false }
        if isEnabled { _ = store.add(kind: .text, data: data) }
        return true
    }

    @discardableResult
    func restore(_ item: ClipboardHistoryItem) -> Bool {
        guard Self.accepts(item.data, kind: item.kind) else { return false }
        checkForChanges()
        guard write(item.data, kind: item.kind) else { return false }
        // Exact-content deduplication keeps existing identities and moves the
        // choice to the front; a choice evicted by the preflight is retained.
        if isEnabled { _ = store.add(kind: item.kind, data: item.data) }
        return true
    }

    private func baseline() {
        observedChangeCount = environment.changeCount()
        ownWriteChangeCount = nil
    }

    private func write(_ data: Data, kind: ClipboardHistoryKind) -> Bool {
        let type: NSPasteboard.PasteboardType
        switch kind {
        case .text: type = .string
        case .png: type = .png
        case .tiff: type = .tiff
        }
        guard observedChangeCount == environment.changeCount(),
              let generation = environment.write(data, type),
              environment.changeCount() == generation else { return false }
        observedChangeCount = generation
        ownWriteChangeCount = generation
        return true
    }

    private static func accepts(_ data: Data, kind: ClipboardHistoryKind) -> Bool {
        guard kind == .text, !data.isEmpty, data.count <= maximumItemByteCount,
              let text = String(data: data, encoding: .utf8) else { return false }
        return !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}
